CREATE TABLE asset (
    id BIGINT NOT NULL AUTO_INCREMENT,
    asset_code VARCHAR(40) NOT NULL,
    asset_name VARCHAR(160) NOT NULL,
    category VARCHAR(80),
    asset_type VARCHAR(80),
    brand VARCHAR(100),
    model VARCHAR(100),
    serial_number VARCHAR(100),
    purchase_date DATE,
    purchase_cost DECIMAL(14,2),
    supplier VARCHAR(120),
    warranty_start DATE,
    warranty_expiry DATE,
    location VARCHAR(120),
    department VARCHAR(120),
    status VARCHAR(32) NOT NULL DEFAULT 'AVAILABLE',
    description VARCHAR(2000),
    created_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT uq_asset_code UNIQUE (asset_code),
    CONSTRAINT uq_asset_serial UNIQUE (serial_number),
    CONSTRAINT chk_asset_cost CHECK (purchase_cost IS NULL OR purchase_cost >= 0),
    CONSTRAINT chk_asset_status CHECK (status IN ('ACTIVE', 'AVAILABLE', 'ASSIGNED', 'UNDER_MAINTENANCE', 'RETIRED')),
    INDEX idx_asset_status (status),
    INDEX idx_asset_department (department),
    INDEX idx_asset_category (category),
    INDEX idx_asset_updated (updated_at)
);
